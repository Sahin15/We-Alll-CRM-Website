import mongoose from "mongoose";
import dotenv from "dotenv";
import Client from "../src/models/clientModel.js";
import Project from "../src/models/projectModel.js";

dotenv.config();

const verifyClientProjects = async () => {
  try {
    // Connect to MongoDB
    await mongoose.connect(process.env.MONGO_URI);
    console.log("✅ Connected to MongoDB");

    // Get all clients
    const allClients = await Client.find({}).select('_id name email company').lean();
    console.log(`📊 Total clients: ${allClients.length}`);

    // Get all projects with client information
    const allProjects = await Project.find({})
      .populate('client', 'name email company')
      .select('name client status createdAt')
      .lean();
    
    console.log(`📊 Total projects: ${allProjects.length}`);

    // Group projects by client
    const projectsByClient = {};
    allProjects.forEach(project => {
      if (project.client) {
        const clientId = project.client._id.toString();
        if (!projectsByClient[clientId]) {
          projectsByClient[clientId] = [];
        }
        projectsByClient[clientId].push(project);
      }
    });

    // Find clients with and without projects
    const clientsWithProjects = [];
    const clientsWithoutProjects = [];

    allClients.forEach(client => {
      const clientId = client._id.toString();
      if (projectsByClient[clientId]) {
        clientsWithProjects.push({
          client,
          projects: projectsByClient[clientId]
        });
      } else {
        clientsWithoutProjects.push(client);
      }
    });

    console.log("\n" + "=".repeat(80));
    console.log("📊 CLIENT-PROJECT VERIFICATION REPORT");
    console.log("=".repeat(80));
    
    console.log(`✅ Clients with projects: ${clientsWithProjects.length}`);
    console.log(`❌ Clients without projects: ${clientsWithoutProjects.length}`);
    
    if (clientsWithoutProjects.length > 0) {
      console.log("\n🚨 CLIENTS WITHOUT PROJECTS:");
      clientsWithoutProjects.forEach((client, index) => {
        console.log(`   ${index + 1}. ${client.name} (${client.email}) - ${client.company || 'No company'}`);
      });
    } else {
      console.log("\n🎉 ALL CLIENTS HAVE PROJECTS!");
    }

    // Show auto-generated projects (created today)
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    
    const autoGeneratedToday = allProjects.filter(project => {
      const projectDate = new Date(project.createdAt);
      projectDate.setHours(0, 0, 0, 0);
      return projectDate.getTime() === today.getTime() && 
             project.name.includes(' Project');
    });

    if (autoGeneratedToday.length > 0) {
      console.log(`\n🤖 AUTO-GENERATED PROJECTS TODAY: ${autoGeneratedToday.length}`);
      autoGeneratedToday.forEach((project, index) => {
        console.log(`   ${index + 1}. ${project.name} (Client: ${project.client?.name || 'Unknown'})`);
      });
    }

    // Show clients with multiple projects
    const clientsWithMultipleProjects = clientsWithProjects.filter(item => item.projects.length > 1);
    if (clientsWithMultipleProjects.length > 0) {
      console.log(`\n📈 CLIENTS WITH MULTIPLE PROJECTS: ${clientsWithMultipleProjects.length}`);
      clientsWithMultipleProjects.forEach((item, index) => {
        console.log(`   ${index + 1}. ${item.client.name} - ${item.projects.length} projects`);
      });
    }

    console.log("\n" + "=".repeat(80));
    console.log("📊 SUMMARY STATISTICS");
    console.log("=".repeat(80));
    console.log(`📊 Total clients: ${allClients.length}`);
    console.log(`📊 Total projects: ${allProjects.length}`);
    console.log(`✅ Clients with projects: ${clientsWithProjects.length} (${((clientsWithProjects.length / allClients.length) * 100).toFixed(1)}%)`);
    console.log(`❌ Clients without projects: ${clientsWithoutProjects.length} (${((clientsWithoutProjects.length / allClients.length) * 100).toFixed(1)}%)`);
    console.log(`🤖 Auto-generated today: ${autoGeneratedToday.length}`);
    console.log(`📈 Clients with multiple projects: ${clientsWithMultipleProjects.length}`);
    console.log("=".repeat(80));

    process.exit(0);
  } catch (error) {
    console.error("❌ Error in verifyClientProjects:", error.message);
    process.exit(1);
  }
};

// Run the script
verifyClientProjects();