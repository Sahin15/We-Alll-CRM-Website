import mongoose from "mongoose";
import WorkCalendar from "../src/models/workCalendarModel.js";
import WorkItem from "../src/models/workItemModel.js";
import dotenv from "dotenv";

// Load environment variables
dotenv.config({ path: './backend/.env' });

const investigateWorkCalendarDates = async () => {
  try {
    console.log("🔍 Connecting to database...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("✅ Connected to database");

    console.log("\n📋 Investigating work calendar entries...");
    
    // Find all work calendar entries
    const workCalendarEntries = await WorkCalendar.find({})
      .populate('sourceId')
      .sort({ createdAt: -1 });

    console.log(`Found ${workCalendarEntries.length} work calendar entries`);

    for (const entry of workCalendarEntries) {
      console.log(`\n📅 Entry: ${entry.title}`);
      console.log(`   ID: ${entry._id}`);
      console.log(`   Source Model: ${entry.sourceModel}`);
      console.log(`   Auto Generated: ${entry.isAutoGenerated}`);
      console.log(`   Start Date: ${entry.startDate.toLocaleString()}`);
      console.log(`   End Date: ${entry.endDate.toLocaleString()}`);
      
      if (entry.dueDate) {
        console.log(`   Due Date: ${entry.dueDate.toLocaleString()}`);
      }
      
      if (entry.sourceId && entry.sourceModel === 'WorkItem') {
        console.log(`   Work Item Due Date: ${entry.sourceId.dueDate.toLocaleString()}`);
        
        // Check if dates span multiple days
        const startDay = entry.startDate.toDateString();
        const endDay = entry.endDate.toDateString();
        const dueDay = entry.sourceId.dueDate.toDateString();
        
        if (startDay !== endDay) {
          console.log(`   ⚠️  SPANS MULTIPLE DAYS: ${startDay} to ${endDay}`);
        }
        
        if (startDay !== dueDay || endDay !== dueDay) {
          console.log(`   ⚠️  DATES DON'T MATCH DUE DATE: Due=${dueDay}, Start=${startDay}, End=${endDay}`);
        }
      }
    }

    // Also check work items
    console.log(`\n📋 Checking work items...`);
    const workItems = await WorkItem.find({}).sort({ createdAt: -1 });
    
    console.log(`Found ${workItems.length} work items`);
    
    for (const item of workItems) {
      console.log(`\n📝 Work Item: ${item.title}`);
      console.log(`   ID: ${item._id}`);
      console.log(`   Due Date: ${item.dueDate.toLocaleString()}`);
      console.log(`   Status: ${item.status}`);
      
      // Check if there's a corresponding calendar entry
      const calendarEntry = await WorkCalendar.findOne({
        sourceId: item._id,
        sourceModel: 'WorkItem'
      });
      
      if (calendarEntry) {
        console.log(`   ✅ Has calendar entry`);
        console.log(`   Calendar Start: ${calendarEntry.startDate.toLocaleString()}`);
        console.log(`   Calendar End: ${calendarEntry.endDate.toLocaleString()}`);
      } else {
        console.log(`   ❌ No calendar entry found`);
      }
    }

  } catch (error) {
    console.error("❌ Error during investigation:", error);
  } finally {
    await mongoose.disconnect();
    console.log("🔌 Disconnected from database");
  }
};

// Run the investigation
investigateWorkCalendarDates();